#!/usr/bin/env bash
# Pull GoogleService-Info.plist for the registered iOS app and derive
# Config/Firebase.xcconfig from it. Neither file is committed: they are
# project-specific, the same way the web dashboard never hardcodes its config
# and reads /__/firebase/init.js instead.
#
#   ./scripts/fetch-firebase-config.sh [project-id] [bundle-id]
#
# The iOS app must already be registered in the Firebase project — see
# docs/ios-app.md. That is a one-time change to the project and is not done here.
set -euo pipefail
cd "$(dirname "$0")/.."

PROJECT="${1:-snof-live}"
BUNDLE="${2:-$(sed -n 's/^SNOF_BUNDLE_ID *= *//p' Config/App.xcconfig)}"

APP_ID="$(firebase apps:list IOS --project "$PROJECT" --json |
  python3 -c "import json,sys; b=sys.argv[1]; apps=json.load(sys.stdin).get('result',[]); m=[a['appId'] for a in apps if a.get('namespace')==b or a.get('bundleId')==b]; print(m[0] if m else '')" "$BUNDLE")"
if [[ -z "$APP_ID" ]]; then
  echo "No iOS app with bundle id $BUNDLE in $PROJECT. Register it first (docs/ios-app.md)." >&2
  exit 1
fi

mkdir -p SNOF/Firebase
firebase apps:sdkconfig IOS "$APP_ID" --project "$PROJECT" --out SNOF/Firebase/GoogleService-Info.plist >/dev/null
REVERSED="$(/usr/libexec/PlistBuddy -c 'Print :REVERSED_CLIENT_ID' SNOF/Firebase/GoogleService-Info.plist 2>/dev/null || true)"
if [[ -z "$REVERSED" ]]; then
  echo "warning: the plist has no REVERSED_CLIENT_ID — enable Google sign-in for $PROJECT and re-run." >&2
fi
cat > Config/Firebase.xcconfig <<XC
// Generated by scripts/fetch-firebase-config.sh — do not commit.
GOOGLE_REVERSED_CLIENT_ID = ${REVERSED:-com.googleusercontent.apps.unconfigured}
XC
echo "Wrote SNOF/Firebase/GoogleService-Info.plist and Config/Firebase.xcconfig for $BUNDLE ($APP_ID)."
echo "Run xcodegen again so the plist is picked up as a resource."
